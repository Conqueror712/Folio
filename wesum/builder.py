class SiteBuilder:
    """
    Generates the complete static HTML website from the database.

    Usage:
        builder = SiteBuilder(config.site, db)
        builder.build()
    """

    def __init__(self, site_config: SiteConfig, db: Database) -> None:
        self.cfg = site_config
        self.db = db
        self.output_dir = Path(site_config.output_dir)
        self.articles_dir = self.output_dir / "articles"
        self.category_dir = self.output_dir / "category"

    def _url(self, path: str) -> str:
        """Construct a URL, using base_url if configured."""
        if self.cfg.base_url:
            return f"{self.cfg.base_url.rstrip('/')}/{path.lstrip('/')}"
        return path  # Relative path for local file:// access

    def _index_url(self, from_subdir: bool = False) -> str:
        if from_subdir:
            return "../index.html"
        return "index.html"

    def _search_json_url(self, from_subdir: bool = False) -> str:
        if from_subdir:
            return "../search.json"
        return "search.json"

    def build(self) -> None:
        """Build the complete static site."""
        logger.info("Building static site → %s", self.output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.articles_dir.mkdir(exist_ok=True)
        self.category_dir.mkdir(exist_ok=True)

        # Create placeholder .gitkeep
        (self.output_dir / ".gitkeep").touch()

        articles = self.db.get_articles(status="processed", order_by="published_at DESC")
        logger.info("Building site for %d processed articles", len(articles))

        # Build pages
        self._build_search_index(articles)
        self._build_index(articles)
        self._build_category_pages(articles)
        self._build_article_pages(articles)

        logger.info("Site build complete: %s", self.output_dir.absolute())

    def _build_search_index(self, articles: List[Article]) -> None:
        """Generate search.json for Fuse.js."""
        data = []
        for a in articles:
            topic_list = a.topic_tags_list()
            data.append({
                "id": a.id,
                "url": f"articles/{a.id}.html",
                "title": a.title,
                "summary": a.summary,
                "source": a.source,
                "type_tag": a.type_tag,
                "topic_tags": " ".join(topic_list),
                "published": _format_date(a.published_at),
            })

        search_path = self.output_dir / "search.json"
        with open(search_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        logger.debug("search.json written (%d items)", len(data))

    def _get_category_links(self, from_subdir: bool = False) -> str:
        """Generate category navigation links."""
        type_tags = self.db.get_type_tags()
        prefix = "../" if from_subdir else ""
        links = []
        for tag in type_tags:
            safe_tag = re.sub(r"[^\w\u4e00-\u9fff-]", "_", tag)
            links.append(
                f'<a href="{prefix}category/{safe_tag}.html" '
                f'class="hover:text-indigo-600 dark:hover:text-indigo-400 transition-colors">'
                f'{tag}</a>'
            )
        return "\n".join(links)

    def _render_head(
        self,
        page_title: str = "首页",
        description: str = "",
        from_subdir: bool = False,
    ) -> str:
        prefix = "../" if from_subdir else ""
        return _HEAD_TEMPLATE.format(
            lang=self.cfg.language,
            description=description or self.cfg.description,
            page_title=page_title,
            site_title=self.cfg.title,
            tailwind_cdn=_TAILWIND_CDN,
        )

    def _render_navbar(self, from_subdir: bool = False) -> str:
        return _NAVBAR_TEMPLATE.format(
            index_url=self._index_url(from_subdir),
            site_title=self.cfg.title,
            category_links=self._get_category_links(from_subdir),
        )

    def _render_footer(self, article_count: int) -> str:
        return _FOOTER_TEMPLATE.format(
            generated_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
            stats_text=f"共 {article_count} 篇文章",
        )

    def _render_scripts(self, from_subdir: bool = False) -> str:
        search_url = self._search_json_url(from_subdir)
        return (
            _THEME_SCRIPT
            + _SEARCH_SCRIPT.format(
                fuse_cdn=_FUSE_CDN,
                search_json_url=search_url,
            )
        )

