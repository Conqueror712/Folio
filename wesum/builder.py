    def _build_article_pages(self, articles: List[Article]) -> None:
        """Build individual article detail pages."""
        # Build a quick lookup for related articles
        for article in articles:
            self._build_single_article_page(article, articles)
        logger.info("Built %d article detail pages", len(articles))

    def _build_single_article_page(
        self, article: Article, all_articles: List[Article]
    ) -> None:
        """Render one article detail page."""
        topic_list = article.topic_tags_list()

        # Related articles: same type_tag or shared topic tags, max 4
        related = []
        for other in all_articles:
            if other.id == article.id:
                continue
            score = 0
            if other.type_tag == article.type_tag:
                score += 1
            other_topics = set(other.topic_tags_list())
            shared = set(topic_list) & other_topics
            score += len(shared)
            if score > 0:
                related.append((score, other))
        related.sort(key=lambda x: -x[0])
        related_articles = [r[1] for r in related[:4]]

        related_html = ""
        if related_articles:
            related_html = """
    <div class="mt-8">
      <h3 class="text-base font-semibold text-gray-700 dark:text-gray-300 mb-3">📎 相关文章</h3>
      <div class="grid grid-cols-1 sm:grid-cols-2 gap-3">"""
            for ra in related_articles:
                related_html += f"""
        <a href="{ra.id}.html" class="block p-3 bg-gray-50 dark:bg-gray-800 rounded-lg hover:bg-indigo-50 dark:hover:bg-indigo-900/20 border border-gray-100 dark:border-gray-700 transition-colors">
          <div class="text-sm font-medium text-gray-800 dark:text-gray-200 line-clamp-2">{ra.title}</div>
          <div class="text-xs text-gray-400 mt-1">{ra.source} · {_format_date(ra.published_at)}</div>
        </a>"""
            related_html += "\n      </div>\n    </div>"

        # Detailed summary section
        if article.detailed_summary:
            summary_content = _markdown_to_html(article.detailed_summary)
            summary_section = f"""
    <div class="bg-white dark:bg-gray-800 rounded-xl shadow-sm border border-gray-100 dark:border-gray-700 p-6 mt-6">
      <h2 class="text-lg font-semibold text-gray-800 dark:text-gray-200 mb-4">🤖 AI 深度摘要</h2>
      <div class="prose dark:prose-invert max-w-none space-y-2">
        {summary_content}
      </div>
    </div>"""
