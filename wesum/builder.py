_TYPE_TAG_COLORS = {
    "干货": "bg-green-100 text-green-700 dark:bg-green-900/50 dark:text-green-300",
    "新闻": "bg-blue-100 text-blue-700 dark:bg-blue-900/50 dark:text-blue-300",
    "广告": "bg-gray-100 text-gray-500 dark:bg-gray-800 dark:text-gray-400",
    "观点": "bg-purple-100 text-purple-700 dark:bg-purple-900/50 dark:text-purple-300",
    "其他": "bg-gray-100 text-gray-600 dark:bg-gray-800 dark:text-gray-400",
}

_CRED_COLORS = {
    "ok": "",
    "clickbait": "text-orange-500 dark:text-orange-400",
    "exaggerated": "text-red-500 dark:text-red-400",
}

_CRED_LABELS = {
    "ok": "",
    "clickbait": "⚠️ 标题党",
    "exaggerated": "🚨 夸大",
}


def _type_tag_html(tag: str) -> str:
    color = _TYPE_TAG_COLORS.get(tag, _TYPE_TAG_COLORS["其他"])
    return f'<span class="tag-badge px-1.5 py-0.5 rounded text-xs font-medium {color}">{tag}</span>'


def _topic_tags_html(tags: List[str]) -> str:
    if not tags:
        return ""
    spans = [
        f'<span class="tag-badge px-1.5 py-0.5 rounded text-xs bg-indigo-50 text-indigo-600 dark:bg-indigo-900/40 dark:text-indigo-300">{t}</span>'
        for t in tags[:3]
    ]
    return " ".join(spans)


def _stars_html(score: int) -> str:
    score = max(0, min(3, score))
    return "⭐" * score if score > 0 else ""


def _credibility_html(cred: str, note: str) -> str:
    if cred == "ok" or not cred:
        return ""
    label = _CRED_LABELS.get(cred, cred)
    color = _CRED_COLORS.get(cred, "")
    title_attr = f' title="{note}"' if note else ""
    return f'<span class="text-xs {color}"{title_attr}>{label}</span>'


def _format_date(dt: Optional[datetime]) -> str:
    if not dt:
        return "-"
    return dt.strftime("%Y-%m-%d")


def _markdown_to_html(md: str) -> str:
    """
    Simple Markdown → HTML converter for detailed summaries.
    Handles: ## headings, ** bold **, * bullet *, > blockquote, plain text.
    """
    lines = md.split("\n")
    html_parts = []
    in_list = False

    for line in lines:
        # Heading
        h2_match = re.match(r"^## (.+)$", line)
        h3_match = re.match(r"^### (.+)$", line)
        if h2_match:
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            html_parts.append(f'<h2 class="text-lg font-semibold text-gray-800 dark:text-gray-200 mt-6 mb-2">{h2_match.group(1)}</h2>')
        elif h3_match:
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            html_parts.append(f'<h3 class="text-base font-semibold text-gray-700 dark:text-gray-300 mt-4 mb-1">{h3_match.group(1)}</h3>')
        elif line.startswith("- ") or line.startswith("* "):
            if not in_list:
                html_parts.append('<ul class="list-disc list-inside space-y-1 text-gray-700 dark:text-gray-300 ml-2">')
                in_list = True
            item = line[2:]
            # Bold within list item
            item = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", item)
            html_parts.append(f"<li>{item}</li>")
        elif line.startswith("> "):
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line[2:])
            html_parts.append(f'<blockquote class="border-l-4 border-indigo-400 pl-4 py-1 my-2 text-gray-600 dark:text-gray-400 italic">{text}</blockquote>')
        elif line.strip() == "":
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            html_parts.append("<br>")
        else:
            if in_list:
                html_parts.append("</ul>")
                in_list = False
            text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
            text = re.sub(r"`(.+?)`", r'<code class="bg-gray-100 dark:bg-gray-800 px-1 rounded text-sm">\1</code>', text)
            html_parts.append(f'<p class="text-gray-700 dark:text-gray-300 leading-relaxed">{text}</p>')

    if in_list:
        html_parts.append("</ul>")

    return "\n".join(html_parts)


